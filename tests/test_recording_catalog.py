from __future__ import annotations

from datetime import datetime
import hashlib
import json
import os
from pathlib import Path
import shutil
import tempfile
import unittest
from unittest.mock import patch

from scripts import jobs, recording_catalog as catalog, recordings, update_project_kanban
from scripts.obsidian import frontmatter


class RecordingCatalogTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / "vault"
        self.task = self.root / "completate" / "Task" / "Alpha"
        self.unassigned = self.root / "completate" / "Senza progetto"
        self.incoming = self.root / "da_processare"
        self.task.mkdir(parents=True)
        self.unassigned.mkdir(parents=True)
        self.incoming.mkdir(parents=True)
        (self.task / "README.md").write_text("# Alpha\n", encoding="utf-8")
        self.timestamp = datetime(2026, 10, 15, 9, 30).timestamp()

    @staticmethod
    def _hash(data: bytes) -> str:
        return hashlib.sha256(data).hexdigest()

    def _saved(
        self,
        *,
        title: str = "Review sync",
        task: Path | None = None,
        archived: bool = False,
        filename: str | None = None,
        data: bytes = b"synthetic saved recording",
        job_id: str = "0123456789abcdef01234567",
        call_job: bool = False,
        extra_media: tuple[str, ...] = (),
    ) -> tuple[Path, Path, str]:
        task_dir = task or self.task
        parent = task_dir / "archivio" if archived else task_dir
        call_dir = parent / f"2026-10-15 09.30 - {title}"
        call_dir.mkdir(parents=True, exist_ok=True)
        source = call_dir / (filename or f"{title}.m4a")
        source.write_bytes(data)
        os.utime(source, (self.timestamp, self.timestamp))
        file_hash = self._hash(data)
        (call_dir / recordings._MARKER).write_text(
            json.dumps(recordings._marker_data(job_id, file_hash, "save")), encoding="utf-8"
        )
        for name in extra_media:
            (call_dir / name).write_bytes(b"generated bytes")
        if call_job:
            (call_dir / ".call-job.json").write_text("{}", encoding="utf-8")
        return call_dir, source, file_hash

    def _trash(
        self,
        *,
        name: str = "2026-10-15 09-10-11.mp4",
        data: bytes = b"synthetic discarded recording",
        job_id: str = "abcdef0123456789abcdef01",
        discarded_at: float | None = None,
        present: bool = True,
        original_path: str | None = None,
    ) -> tuple[Path, Path, str]:
        directory = self.root / "cestino_registrazioni" / job_id
        directory.mkdir(parents=True)
        source = directory / name
        file_hash = self._hash(data)
        (directory / recordings._MARKER).write_text(
            json.dumps(recordings._marker_data(job_id, file_hash, "discard")), encoding="utf-8"
        )
        if present:
            source.write_bytes(data)
            os.utime(source, (self.timestamp, self.timestamp))
        metadata = {
            "id": job_id,
            "name": name,
            "original_path": original_path or str(self.incoming / name),
            "discarded_at": discarded_at if discarded_at is not None else self.timestamp,
            "sha256": file_hash,
        }
        (directory / "metadata.json").write_text(json.dumps(metadata), encoding="utf-8")
        return directory, source, file_hash

    def _job(
        self,
        *,
        recording_id: str,
        category: str,
        file_hash: str,
        source: Path,
        complete: bool = False,
        timestamp: float | None = None,
    ) -> dict:
        state = {
            "id": hashlib.sha256(f"job:{recording_id}:{category}".encode()).hexdigest()[:24],
            "source": str(source),
            "timestamp": self.timestamp if timestamp is None else timestamp,
            "complete": complete,
            "recording_context": {
                "recording_id": recording_id,
                "category": category,
                "sha256": file_hash,
                "timestamp": self.timestamp,
                "source": str(source),
            },
        }
        jobs.save_job(self.root, state)
        return state

    def test_lists_saved_archived_unassigned_and_trash_items_without_generated_audio(self) -> None:
        active_dir, active_source, active_hash = self._saved(
            extra_media=("audio.m4a", "audio_compresso.m4a", "voice.part.tmp.m4a")
        )
        archive_dir, archive_source, archive_hash = self._saved(
            title="Archived sync", archived=True, job_id="111111111111111111111111"
        )
        unassigned_dir, unassigned_source, unassigned_hash = self._saved(
            title="No task", task=self.unassigned, job_id="222222222222222222222222"
        )
        trash_dir, trash_source, trash_hash = self._trash()

        items = catalog.list_unprocessed(self.root)
        by_source = {item["source"]: item for item in items}
        self.assertEqual({str(active_source), str(archive_source), str(unassigned_source), str(trash_source)}, set(by_source))
        self.assertEqual(active_hash, by_source[str(active_source)]["sha256"])
        self.assertEqual(str(self.task), by_source[str(active_source)]["task_dir"])
        self.assertEqual("Alpha", by_source[str(active_source)]["task_name"])
        self.assertEqual("Review sync", by_source[str(active_source)]["title"])
        self.assertEqual(str(self.task), by_source[str(archive_source)]["task_dir"])
        self.assertEqual("Alpha", by_source[str(archive_source)]["task_name"])
        self.assertEqual(str(self.unassigned), by_source[str(unassigned_source)]["task_dir"])
        self.assertEqual("", by_source[str(unassigned_source)]["task_name"])
        self.assertEqual("trash", by_source[str(trash_source)]["category"])
        self.assertEqual("ready", by_source[str(trash_source)]["status"])
        self.assertEqual(self.timestamp, by_source[str(trash_source)]["timestamp"])
        self.assertEqual(self.timestamp, by_source[str(trash_source)]["discarded_at"])
        self.assertTrue(active_dir.is_dir() and archive_dir.is_dir() and unassigned_dir.is_dir() and trash_dir.is_dir())
        self.assertEqual(archive_hash, by_source[str(archive_source)]["sha256"])
        self.assertEqual(unassigned_hash, by_source[str(unassigned_source)]["sha256"])
        self.assertEqual(trash_hash, by_source[str(trash_source)]["sha256"])

    def test_pending_recording_is_not_removed_by_expired_trash_cleanup(self) -> None:
        directory, source, file_hash = self._trash(discarded_at=self.timestamp - 31 * 86400)
        job = self._job(recording_id=directory.name, category="trash", file_hash=file_hash, source=source)

        protected = catalog.protected_trash_dirs(self.root)
        self.assertEqual(recordings.cleanup_trash(self.root, now=self.timestamp, excluded_dirs=protected), 0)
        self.assertTrue(source.is_file())

        job["complete"] = True
        jobs.save_job(self.root, job)
        self.assertEqual(catalog.protected_trash_dirs(self.root), set())
        self.assertEqual(recordings.cleanup_trash(self.root, now=self.timestamp), 1)

    def test_alternate_compressed_output_does_not_hide_original_named_audio_compresso(self) -> None:
        _, source, file_hash = self._saved(title="audio_compresso", extra_media=("audio_elaborato.m4a",))
        self._job(recording_id="0123456789abcdef01234567", category="saved",
                  file_hash=file_hash, source=source)

        items = catalog.list_unprocessed(self.root)

        self.assertEqual(len(items), 1)
        self.assertEqual(items[0]["source"], str(source))

    def test_original_named_audio_is_kept_when_it_is_the_only_media_candidate(self) -> None:
        _directory, source, file_hash = self._saved(
            title="audio", filename="audio.m4a", job_id="333333333333333333333333"
        )
        item = catalog.list_unprocessed(self.root)[0]
        self.assertEqual(str(source), item["source"])
        self.assertEqual(file_hash, item["sha256"])

    def test_original_name_with_part_segment_matching_title_is_kept(self) -> None:
        _directory, source, _file_hash = self._saved(
            title="sync.part", filename="sync.part.m4a", job_id="444444444444444444444444"
        )
        items = catalog.list_unprocessed(self.root)
        self.assertEqual([str(source)], [item["source"] for item in items])

    def test_pending_saved_recording_follows_folder_moved_into_archive(self) -> None:
        call_dir, source, file_hash = self._saved()
        self._job(
            recording_id="0123456789abcdef01234567", category="saved", file_hash=file_hash, source=source
        )
        archive_dir = self.task / "archivio"
        archive_dir.mkdir()
        moved_dir = call_dir.rename(archive_dir / call_dir.name)
        moved_source = moved_dir / source.name

        items = catalog.list_unprocessed(self.root)
        self.assertEqual(1, len(items))
        self.assertEqual(str(moved_source), items[0]["source"])
        self.assertEqual(str(moved_dir), items[0]["existing_dir"])
        self.assertEqual("interrupted", items[0]["status"])

    def test_pending_folder_copy_is_not_selected_while_old_source_remains(self) -> None:
        call_dir, source, file_hash = self._saved()
        self._job(
            recording_id="0123456789abcdef01234567", category="saved", file_hash=file_hash, source=source
        )
        archive_dir = self.task / "archivio"
        archive_dir.mkdir()
        shutil.copytree(call_dir, archive_dir / call_dir.name)

        items = catalog.list_unprocessed(self.root)
        self.assertEqual(1, len(items))
        self.assertEqual(str(source), items[0]["source"])
        self.assertEqual(str(call_dir), items[0]["existing_dir"])

    def test_listing_reads_metadata_and_stats_media_but_never_opens_source(self) -> None:
        _directory, source, _file_hash = self._saved()
        original_open = Path.open

        def guarded_open(path: Path, *args, **kwargs):
            if path == source:
                raise AssertionError("listing attempted to read recording bytes")
            return original_open(path, *args, **kwargs)

        with patch.object(Path, "open", guarded_open):
            listed = catalog.list_unprocessed(self.root)
        self.assertEqual(1, len(listed))

    def test_expired_trash_is_hidden_except_when_an_incomplete_job_can_resume_it(self) -> None:
        old = self.timestamp - 31 * 24 * 60 * 60
        _directory, source, file_hash = self._trash(discarded_at=old)
        self.assertEqual([], catalog.list_unprocessed(self.root))

        self._job(
            recording_id="abcdef0123456789abcdef01", category="trash", file_hash=file_hash, source=source
        )
        listed = catalog.list_unprocessed(self.root)
        self.assertEqual(1, len(listed))
        self.assertEqual("interrupted", listed[0]["status"])

    def test_missing_source_is_listed_only_for_a_matching_incomplete_checkpoint(self) -> None:
        _directory, source, file_hash = self._trash(present=False)
        self.assertEqual([], catalog.list_unprocessed(self.root))
        self._job(
            recording_id="abcdef0123456789abcdef01", category="trash", file_hash=file_hash, source=source
        )
        listed = catalog.list_unprocessed(self.root)
        self.assertEqual(str(source), listed[0]["source"])
        self.assertEqual("interrupted", listed[0]["status"])

    def test_call_job_directory_needs_matching_pending_job_and_complete_job_reconciles_both_categories(self) -> None:
        _directory, saved_source, saved_hash = self._saved(call_job=True)
        _trash_dir, trash_source, trash_hash = self._trash()
        self.assertEqual({str(trash_source)}, {item["source"] for item in catalog.list_unprocessed(self.root)})
        self._job(
            recording_id="0123456789abcdef01234567", category="saved", file_hash=saved_hash,
            source=saved_source, complete=True,
        )
        self._job(
            recording_id="abcdef0123456789abcdef01", category="trash", file_hash=trash_hash,
            source=trash_source, complete=True,
        )
        self.assertEqual([], catalog.list_unprocessed(self.root))

    def test_matching_pending_job_makes_call_job_directory_resumable(self) -> None:
        _directory, source, file_hash = self._saved(call_job=True)
        self._job(
            recording_id="0123456789abcdef01234567", category="saved", file_hash=file_hash, source=source
        )
        items = catalog.list_unprocessed(self.root)
        self.assertEqual(1, len(items))
        self.assertEqual("interrupted", items[0]["status"])

    def test_old_pending_checkpoint_for_reused_path_does_not_change_new_item_status(self) -> None:
        _directory, source, file_hash = self._saved()
        self._job(
            recording_id="999999999999999999999999", category="saved",
            file_hash=self._hash(b"previous recording"), source=source,
        )
        items = catalog.list_unprocessed(self.root)
        self.assertEqual(1, len(items))
        self.assertEqual("ready", items[0]["status"])
        self.assertEqual(file_hash, items[0]["sha256"])

    def test_process_recording_passes_signature_context_and_pipeline_options(self) -> None:
        _directory, source, file_hash = self._saved()
        item = catalog.list_unprocessed(self.root)[0]
        result = {"summary": "synthetic"}
        with patch("scripts.watch_calls._file_available", return_value=True), patch(
            "scripts.process_call.process", return_value=result
        ) as process:
            returned = catalog.process_recording(self.root, item, summary_model="test-model")
        self.assertIs(result, returned)
        kwargs = process.call_args.kwargs
        stat = source.stat()
        self.assertEqual(source, kwargs["input_path"])
        self.assertEqual(self.root.resolve(), kwargs["root"])
        self.assertEqual([stat.st_size, stat.st_mtime_ns], kwargs["expected_signature"])
        self.assertEqual("test-model", kwargs["summary_model"])
        self.assertEqual(
            {
                "recording_id": "0123456789abcdef01234567",
                "sha256": file_hash,
                "category": "saved",
                "timestamp": self.timestamp,
                "existing_dir": str(source.parent),
                "title": "Review sync",
                "task_dir": str(self.task),
                "task_name": "Alpha",
            },
            kwargs["recording_context"],
        )

    def test_process_recording_trash_passes_context_without_mutating_trash_metadata(self) -> None:
        directory, source, file_hash = self._trash()
        item = catalog.list_unprocessed(self.root)[0]
        metadata_path = directory / "metadata.json"
        marker_path = directory / recordings._MARKER
        before_metadata = metadata_path.read_bytes()
        before_marker = marker_path.read_bytes()
        with patch("scripts.watch_calls._file_available", return_value=True), patch(
            "scripts.process_call.process", return_value={"ok": True}
        ) as process:
            self.assertEqual({"ok": True}, catalog.process_recording(self.root, item))
        context = process.call_args.kwargs["recording_context"]
        self.assertEqual("trash", context["category"])
        self.assertEqual(file_hash, context["sha256"])
        self.assertEqual(self.timestamp, context["discarded_at"])
        self.assertEqual(before_metadata, metadata_path.read_bytes())
        self.assertEqual(before_marker, marker_path.read_bytes())
        self.assertTrue(source.is_file())

    def test_process_recording_rejects_mutated_content_before_calling_pipeline(self) -> None:
        _directory, source, _file_hash = self._saved()
        item = catalog.list_unprocessed(self.root)[0]
        source.write_bytes(b"changed synthetic bytes")
        with patch("scripts.watch_calls._file_available", return_value=True), patch(
            "scripts.process_call.process"
        ) as process:
            with self.assertRaisesRegex(ValueError, "contenuto.*cambiato"):
                catalog.process_recording(self.root, item)
        process.assert_not_called()

    def test_process_recording_resumes_missing_source_using_pending_checkpoint(self) -> None:
        _directory, source, file_hash = self._trash(present=False)
        self._job(
            recording_id="abcdef0123456789abcdef01", category="trash", file_hash=file_hash, source=source
        )
        item = catalog.list_unprocessed(self.root)[0]
        with patch("scripts.process_call.process", return_value={"resumed": True}) as process:
            result = catalog.process_recording(self.root, item)
        self.assertEqual({"resumed": True}, result)
        kwargs = process.call_args.kwargs
        self.assertEqual(source, kwargs["input_path"])
        self.assertIsNone(kwargs["expected_signature"])
        self.assertEqual("trash", kwargs["recording_context"]["category"])
        self.assertEqual(file_hash, kwargs["recording_context"]["sha256"])

    def test_process_recording_refuses_stale_path_or_identity_without_running_pipeline(self) -> None:
        _directory, source, _file_hash = self._saved()
        item = catalog.list_unprocessed(self.root)[0]
        item["source"] = str(self.incoming / "other.m4a")
        with patch("scripts.process_call.process") as process:
            with self.assertRaisesRegex(ValueError, "percorso.*cambiato"):
                catalog.process_recording(self.root, item)
        process.assert_not_called()

    def test_protected_trash_dirs_includes_missing_sources_of_incomplete_jobs(self) -> None:
        directory, source, file_hash = self._trash(present=False)
        self._job(
            recording_id="abcdef0123456789abcdef01", category="trash", file_hash=file_hash, source=source
        )
        self.assertEqual({directory}, catalog.protected_trash_dirs(self.root))

    def test_protected_trash_dirs_ignores_completed_and_non_trash_jobs(self) -> None:
        trash_dir, trash_source, trash_hash = self._trash()
        saved_dir, saved_source, saved_hash = self._saved()
        self._job(
            recording_id="abcdef0123456789abcdef01", category="trash", file_hash=trash_hash,
            source=trash_source, complete=True,
        )
        self._job(
            recording_id="0123456789abcdef01234567", category="saved", file_hash=saved_hash,
            source=saved_source,
        )
        self.assertNotIn(trash_dir, catalog.protected_trash_dirs(self.root))
        self.assertNotIn(saved_dir, catalog.protected_trash_dirs(self.root))

    def test_trash_listing_rejects_metadata_name_that_escapes_item_directory(self) -> None:
        directory, _source, _file_hash = self._trash()
        metadata_path = directory / "metadata.json"
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        metadata["name"] = "..\\outside.m4a"
        metadata_path.write_text(json.dumps(metadata), encoding="utf-8")
        self.assertEqual([], catalog.list_unprocessed(self.root))

    def test_solo_registrazione_note_does_not_initialize_provider_for_kanban(self) -> None:
        summary = self.task / "2026-10-15 09.30 - Review sync" / "Review sync.md"
        summary.parent.mkdir()
        summary.write_text(
            frontmatter.render_frontmatter(
                {
                    "data": "2026-10-15", "ora": "09:30", "task": "[[Alpha]]", "persone": [],
                    "sistemi": [], "tags": ["call"], "modalita": "solo_registrazione",
                },
                "# Review sync\n\n[[Review sync.m4a]]\n\nRegistrazione presente, ma non trascritta.\n",
            ),
            encoding="utf-8",
        )
        with patch.object(update_project_kanban, "get_provider", side_effect=AssertionError("provider lookup")):
            self.assertEqual(0, update_project_kanban.update_from_summary(summary, self.task))


